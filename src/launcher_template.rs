/// Customizes the launcher's `main.rs` template with real paths and
/// the tarball hash. Returns the Rust code ready to write to the
/// launcher's Cargo project.
///
/// Paths are escaped to be valid Rust string literals (Windows
/// backslashes → `\\`, double quotes → `\"`).
///
/// Phase 8.c — If `pip_packages_path` is `Some(<path>)`, the launcher
/// embeds a second tarball with pre-installed pip packages and
/// extracts them into `python/Lib/site-packages/` after the base PBS
/// extract. If `None` (without `--bundle-pip`), the pip blocks are
/// replaced with empty strings — the resulting launcher is
/// bit-by-bit identical to 8.b.
pub fn gen_launcher_main_rs(
    tarball_path: &str,
    real_binary_path: &str,
    tarball_hash: &str,
    pip_packages_path: Option<&str>,
) -> String {
    let (pip_decl_block, pip_extract_block) = match pip_packages_path {
        Some(path) => (
            format!(
                "const PIP_PACKAGES: &[u8] = include_bytes!(\"{}\");",
                escape_rust_string_literal(path)
            ),
            // Block emitted after `let _ = fs::remove_file(&tarball_path);`.
            // Writes the pip tarball to a temp .tar.gz + extracts it to
            // python/Lib/site-packages/. Assumes `python/` already exists
            // after the base PBS extraction. strip-components=0 preserves
            // the tarball's relative hierarchy (it must contain the
            // package dirs directly).
            r#"
    // Phase 8.c — extraction of embedded pip packages.
    let pip_tarball_path = tmp.join("__fitz_pip.tar.gz");
    fs::write(&pip_tarball_path, PIP_PACKAGES)?;

    let site_packages = tmp.join("python").join("Lib").join("site-packages");
    if !site_packages.exists() {
        // Linux/macOS: the dir lives at python/lib/python3.X/site-packages/.
        // Look for any python3* dir inside python/lib/.
        let py_lib = tmp.join("python").join("lib");
        if py_lib.exists() {
            for entry in fs::read_dir(&py_lib)? {
                let entry = entry?;
                let name = entry.file_name();
                let name_str = name.to_string_lossy();
                if name_str.starts_with("python3") {
                    let sp = entry.path().join("site-packages");
                    if !sp.exists() {
                        fs::create_dir_all(&sp)?;
                    }
                    // v0.9.46 — extract via tar+flate2 inline (sin subprocess).
                    extract_tar_gz(&pip_tarball_path, &sp).map_err(|e| {
                        std::io::Error::new(
                            std::io::ErrorKind::Other,
                            format!("pip packages tar extraction failed: {e}"),
                        )
                    })?;
                    break;
                }
            }
        }
    } else {
        // Windows: python/Lib/site-packages/ ya existe en el PBS.
        // v0.9.46 — extract via tar+flate2 inline (sin subprocess).
        extract_tar_gz(&pip_tarball_path, &site_packages).map_err(|e| {
            std::io::Error::new(
                std::io::ErrorKind::Other,
                format!("pip packages tar extraction failed: {e}"),
            )
        })?;
    }
    let _ = fs::remove_file(&pip_tarball_path);"#
                .to_string(),
        ),
        None => (String::new(), String::new()),
    };

    LAUNCHER_MAIN_RS_TEMPLATE
        .replace(
            PLACEHOLDER_TARBALL_PATH,
            &escape_rust_string_literal(tarball_path),
        )
        .replace(
            PLACEHOLDER_REAL_BINARY_PATH,
            &escape_rust_string_literal(real_binary_path),
        )
        .replace(
            PLACEHOLDER_TARBALL_HASH,
            &escape_rust_string_literal(tarball_hash),
        )
        .replace(PLACEHOLDER_PIP_DECL_BLOCK, &pip_decl_block)
        .replace(PLACEHOLDER_PIP_EXTRACT_BLOCK, &pip_extract_block)
}

/// Customizes the launcher's Cargo.toml template with the final
/// binary name.
pub fn gen_launcher_cargo_toml(bin_name: &str) -> String {
    LAUNCHER_CARGO_TOML_TEMPLATE.replace(PLACEHOLDER_BIN_NAME, bin_name)
}

/// Escapes a string so it is a valid Rust string literal. Handles
/// backslash (Windows paths), double quote, and newlines.
fn escape_rust_string_literal(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
}

/// Computes a deterministic short hash (16 hex chars) of the PBS
/// tarball. Uses a simple 64-bit FNV-1a implementation — it does not
/// need to be cryptographic, just uniquely identify the tarball
/// contents for the dir name in `$TMPDIR`.
///
/// FNV-1a is enough because:
///  - The input is a known PBS tarball (no adversarial attacker).
///  - Accidental collision between two different PBS tarballs is
///    astronomically improbable.
///  - Zero deps: 8-LoC implementation.
pub fn tarball_hash_short(tarball_bytes: &[u8]) -> String {
    const FNV_OFFSET: u64 = 0xcbf2_9ce4_8422_2325;
    const FNV_PRIME: u64 = 0x100_0000_01b3;
    let mut hash: u64 = FNV_OFFSET;
    for b in tarball_bytes {
        hash ^= *b as u64;
        hash = hash.wrapping_mul(FNV_PRIME);
    }
    format!("{:016x}", hash)
}

