/// v0.9.46 — In-memory tar.gz extraction without invoking a system
/// subprocess. Enables minimal runtimes like distroless
/// (`gcr.io/distroless/cc-debian12` ~22 MB base) that do NOT ship
/// shell utilities. Pre-fix, extraction used a subprocess and the
/// minimum viable runtime was `debian:bookworm-slim` (~85 MB base).
/// `tar` + `flate2` crates add ~80-100 KB to the final launcher binary
/// (LTO + strip are enabled in release).
fn extract_tar_gz(tarball_path: &Path, dest: &Path) -> std::io::Result<()> {
    let f = fs::File::open(tarball_path)?;
    let gz = flate2::read::GzDecoder::new(f);
    let mut archive = tar::Archive::new(gz);
    // `unpack` validates paths: rejects absolute paths and `../` that
    // would escape `dest` (CVE protection from the `tar` crate). PBS
    // and pip tarballs are trusted (generated by `fitz build`), but
    // the defensive check does not hurt.
    archive.unpack(dest)?;
    Ok(())
}

const PBS_TARBALL: &[u8] = include_bytes!("__FITZ_REPLACE_PBS_TARBALL_PATH__");
const REAL_BINARY: &[u8] = include_bytes!("__FITZ_REPLACE_REAL_BINARY_PATH__");
